// Browser acceptance against the local synthetic preview only.
import assert from 'node:assert/strict'
import { mkdir, writeFile } from 'node:fs/promises'
import { pathToFileURL } from 'node:url'
const { chromium } = await import(pathToFileURL(process.env.PROVIDER_PLAYWRIGHT_PATH || 'C:/projects/cozyhealth/output/dashboard-test-tools/node_modules/playwright/index.mjs').href)
const base = 'http://127.0.0.1:3100'
const browser = await chromium.launch({ channel: 'msedge', headless: true })
const directory = 'scratch/redesign-review'
await mkdir(directory, { recursive: true })
const checks = [], errors = []
const context = await browser.newContext({ viewport: { width: 1440, height: 1050 } })
const page = await context.newPage()
page.setDefaultTimeout(30000); page.setDefaultNavigationTimeout(120000)
page.on('pageerror', error => errors.push(error.message))
page.on('console', message => { if (message.type() === 'error' && /hydration|hydrated|TypeError|ReferenceError/.test(message.text())) errors.push(message.text().slice(0,200)) })
async function capture(name) {
  await page.waitForFunction(() => ![...document.querySelectorAll('main .animate-pulse')].some(el => el.getBoundingClientRect().height > 0))
  const ready = page.locator('.workspace-collapse'); if (await ready.count()) await page.waitForFunction(() => !document.querySelector('.workspace-collapse')?.disabled)
  await page.addStyleTag({ content: 'nextjs-portal { display:none!important }' })
  await page.evaluate(() => document.fonts.ready)
  await page.screenshot({ path: `${directory}/${name}.png`, fullPage: true, animations: 'disabled' })
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true, `${name}: horizontal page overflow`)
  checks.push(name)
}
try {
  await page.goto(base + '/__preview/provider')
  await page.getByRole('heading', { name: 'Overview', exact: true }).waitFor()
  await page.getByRole('button', { name: 'Appearance and layout' }).waitFor()
  await page.getByRole('button', { name: /Switch to (light|dark) mode/ }).filter({ visible: true }).waitFor()
  await page.waitForFunction(() => !document.querySelector('.workspace-collapse')?.disabled)
  if (await page.getByRole('button', { name: 'Switch to dark mode', exact: true }).filter({ visible: true }).count()) await page.getByRole('button', { name: 'Switch to dark mode', exact: true }).filter({ visible: true }).click()
  await capture('provider-overview-dark')
  await page.getByRole('button', { name: /workspace guide/i }).click()
  await page.getByRole('dialog').waitFor()
  while (await page.getByRole('button', { name: 'Back', exact: true }).count()) { await page.getByRole('button', { name: 'Back', exact: true }).click() }
  await capture('provider-onboarding')
  await page.getByRole('button', { name: 'Next', exact: true }).click()
  await page.getByRole('heading', { name: 'Start with your patients' }).waitFor()
  await page.getByRole('button', { name: 'Continue later', exact: true }).click()
  await page.getByRole('dialog').waitFor({ state: 'hidden' })
  await page.getByRole('button', { name: 'Open insights', exact: true }).click()
  await page.getByRole('heading', { name: 'Intensity pattern', exact: true }).waitFor()
  await page.locator('.care-trend-chart .recharts-line-curve').first().waitFor()
  assert.equal(await page.locator('.care-trend-chart').first().locator('.recharts-line-dot').count(), 7)
  await capture('provider-patient-trend-dark')
  await page.getByRole('button', { name: 'Switch to light mode', exact: true }).filter({visible:true}).click()
  await page.waitForFunction(() => !document.documentElement.classList.contains('dark'))
  await capture('provider-patient-trend-light')
  const insightRoute = '**/api/provider/clients/10/insights?*'
  await page.route(insightRoute, async route => {
    const response = await route.fetch(), body = await response.json()
    body.data.buckets[3].average_intensity = null
    await route.fulfill({response,json:body})
  })
  await page.getByRole('button', { name: 'Refresh insights', exact: true }).click()
  await page.waitForFunction(() => {
    const path = document.querySelector('.care-trend-chart .recharts-line-curve')?.getAttribute('d') || ''
    return (path.match(/M/g) || []).length === 2
  })
  checks.push('missing-intensity-preserves-gap')
  await page.unroute(insightRoute)
  await page.getByRole('button', { name: 'Refresh insights', exact: true }).click()
  await page.getByRole('heading', { name: 'Intensity pattern', exact: true }).waitFor()
  await page.setViewportSize({width:320,height:900})
  await capture('provider-patient-trend-phone')
  await page.setViewportSize({width:1440,height:1050})
  await page.getByRole('tab', { name: 'Other shared data', exact: true }).click()
  await page.locator('.care-shared-journal').waitFor()
  await capture('provider-shared-journal-light')
  await page.getByRole('button', { name: 'Switch to dark mode', exact: true }).filter({visible:true}).click()
  await page.getByRole('button', { name: 'Messages', exact: true }).click()
  await page.getByRole('complementary', { name: 'Conversations' }).waitFor()
  await page.getByRole('textbox', { name: 'Message', exact: true }).waitFor()
  await page.getByRole('region', { name: 'Conversation', exact: true }).getByText('Synthetic conversation one', { exact: true }).waitFor()
  await capture('provider-messages-dark')
  await page.getByRole('button', { name: 'Settings', exact: true }).click()
  await page.getByRole('button', { name: 'Appearance & layout', exact: true }).click()
  await page.getByRole('heading', { name: 'Appearance & layout', exact: true }).waitFor()
  await page.getByRole('button', { name: 'Light', exact: true }).click()
  await page.waitForFunction(() => !document.documentElement.classList.contains('dark'))
  await page.getByRole('button', { name: 'Teal', exact: true }).click()
  await page.waitForFunction(() => document.documentElement.dataset.cozyAccent === 'teal')
  await page.getByRole('button', { name: /Focus.*More room/ }).click()
  await page.waitForFunction(() => document.querySelector('.workspace-app')?.dataset.layout === 'focus')
  await page.getByRole('button', { name: 'compact', exact: true }).click()
  await page.waitForFunction(() => document.documentElement.dataset.cozyDensity === 'compact')
  await capture('provider-settings-light-teal-focus')
  const fresh = await browser.newContext({ viewport: { width: 1440, height: 1000 } })
  const second = await fresh.newPage(); await second.goto(base + '/__preview/provider')
  await second.waitForFunction(() => document.querySelector('.workspace-app')?.dataset.layout === 'focus' && document.documentElement.dataset.cozyAccent === 'teal')
  assert.equal(await second.locator('html').evaluate(el => el.classList.contains('dark')), false)
  checks.push('account-preferences-follow-fresh-browser-context'); await fresh.close()
  await page.getByRole('button', { name: 'Reset appearance', exact: true }).click()
  await page.waitForFunction(() => document.querySelector('.workspace-app')?.dataset.layout === 'overview' && document.documentElement.dataset.cozyAccent === 'blue')
  await page.getByRole('button', { name: 'Messages', exact: true }).click()
  await page.setViewportSize({ width: 390, height: 844 })
  await page.getByRole('complementary', { name: 'Conversations' }).waitFor({ state: 'visible' })
  await capture('messages-phone-list')
  await page.locator('.workspace-thread-item').first().click()
  await page.getByRole('button', { name: 'Back to conversations' }).waitFor({ state: 'visible' })
  await capture('messages-phone-thread')
  await page.getByRole('button', { name: 'Back to conversations' }).click()
  await page.getByRole('complementary', { name: 'Conversations' }).waitFor({ state: 'visible' })
  await page.setViewportSize({ width: 1440, height: 1050 })
  await page.goto(base + '/__preview/admin')
  await page.getByRole('navigation', { name: 'Admin navigation' }).waitFor()
  await capture('admin-overview')
  for (const [path, name] of [['/admin/settings', 'admin-settings'], ['/admin/manage/users', 'admin-users'], ['/admin/datacenter', 'admin-analytics'], ['/admin/safety', 'admin-safety'], ['/admin/manage/articles', 'admin-articles'], ['/admin/manage/community-moderation', 'admin-restrictions']]) {
    await page.goto(base + path)
    await page.getByRole('main').waitFor()
    await capture(name)
  }
  await page.setViewportSize({ width: 390, height: 844 })
  await page.goto(base + '/admin/settings')
  await page.getByRole('heading', { name: 'Appearance & layout' }).waitFor()
  await capture('admin-settings-phone')
  assert.deepEqual(errors, [])
  await writeFile(`${directory}/result.json`, JSON.stringify({ passed: true, checks, pageErrors: errors }, null, 2))
  console.log(JSON.stringify({ passed: true, checks: checks.length, pageErrors: errors }))
} catch (error) {
  await page.screenshot({ path: `${directory}/failure.png`, fullPage: true }).catch(() => {})
  await writeFile(`${directory}/failure.txt`, String(error) + '\n' + await page.locator('body').innerText().catch(() => ''))
  console.error(error); process.exitCode = 1
} finally { await browser.close() }
